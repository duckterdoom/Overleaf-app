import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const compile=file=>ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const url=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const group=url(compile('lib/writing/assessment.ts'));
const code=compile('lib/writing/list-filters.ts').replace(/from ["']\.\/assessment["']/,`from "${group}"`);
const {matchesSearch,matchesAssignment,matchesSubmission,emptyWritingFilters}=await import(url(code));
const filter=values=>({...emptyWritingFilters(),...values});
const course={id:'course-a',title:'Academic writing',students:[{id:'student-a',displayName:'Nguyễn Đạt',studentCode:'ST-204'}]};
const assignment={title:'Chart response',description:'Compare population trends',tutorName:'Alex',category:'ielts',tasks:[1],classId:'course-a',published:true};
const now=Date.UTC(2026,10,19,12);
const row={assignment,studentId:'student-a',studentName:'Dat Nguyen',tutorId:'tutor-a',submittedAt:new Date(now).toISOString()};
assert.ok(matchesSearch('nguyen dat','Nguyễn Đạt'));
assert.ok(matchesSearch('  NGUYEN   ST-204 ',course.students[0].displayName,'ST-204'));
assert.ok(!matchesSearch('missing',null,undefined));
assert.ok(matchesAssignment(assignment,filter({query:'trends academic',course:'course-a',category:'ielts',task:'1',status:'assigned'}),course));
assert.ok(!matchesAssignment(assignment,filter({task:'2'}),course));
assert.ok(!matchesAssignment(assignment,filter({course:'none'}),course));
assert.ok(matchesAssignment({...assignment,classId:null},filter({course:'none'})));
assert.ok(matchesAssignment({...assignment,published:false},filter({status:'draft'})));
assert.ok(matchesAssignment(assignment,filter({status:'submitted'}),course,true));
assert.ok(!matchesAssignment(assignment,filter({status:'not-submitted'}),course,true));
assert.ok(matchesAssignment({...assignment,category:'report'},filter({category:'research'})));
assert.ok(!matchesAssignment({...assignment,category:'report'},filter({task:'1'})));
assert.ok(matchesSubmission(row,filter({query:'nguyen st-204 chart',status:'awaiting',period:'7'}),course,now));
assert.ok(!matchesSubmission(row,filter({query:'missing-code'}),course,now));
assert.ok(matchesSubmission({...row,result:{}},filter({status:'published'}),course,now));
assert.ok(!matchesSubmission(row,filter({status:'published'}),course,now));
assert.ok(matchesSubmission({...row,tutorId:null},filter({status:'personal'}),course,now));
for(const [offset,expected] of [[0,true],[-7*86400000,true],[-7*86400000-1,false],[1,false]])
 assert.equal(matchesSubmission({...row,submittedAt:new Date(now+offset).toISOString()},filter({period:'7'}),course,now),expected);
assert.ok(!matchesSubmission({...row,submittedAt:'invalid'},filter({period:'7'}),course,now));
assert.equal(assignment.category,'ielts');
assert.equal(course.students[0].studentCode,'ST-204');
console.log('LIST_FILTERS_OK combined filters, accent-insensitive search, course/student codes, report grouping, tasks, states and date boundaries');
