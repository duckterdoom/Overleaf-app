import {chromium,expect} from '@playwright/test';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const repo=path.resolve('../..'),out=path.join(repo,'target/latex-ielts-design');
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1600,height:1050}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(repo,'docs/prototypes/writing/index.html')).href);
 await page.getByRole('textbox',{name:'Bài viết Task 2'}).fill('Public transport can reduce traffic. The cost is 10% & budgets matter.');
 await page.getByRole('button',{name:'Tạo/cập nhật LaTeX',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Tạo source',exact:true}).click();
 expect(await page.locator('#latex-answer').inputValue()).toContain('10\\% \\&');
 await page.getByRole('button',{name:'Kiểm tra và nộp',exact:true}).click();
 await page.getByRole('button',{name:'Xác nhận nộp',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Xác nhận nộp',exact:true}).click();
 await page.locator('#role').selectOption('teacher');
 await page.getByRole('button',{name:'Mở bài chấm',exact:true}).click();
  await page.getByRole('button',{name:'Tổng kết band',exact:true}).click();
 await page.getByRole('button',{name:'LaTeX source',exact:true}).click();
 await expect(page.locator('.readonly-source')).toContainText('Public transport can reduce traffic.');
 await expect(page.getByRole('combobox',{name:'Band TR',exact:true})).toBeVisible();
 await page.screenshot({path:path.join(out,'tutor-latex-and-band.png')});
 await page.getByRole('button',{name:'PDF preview',exact:true}).click();
 await expect(page.locator('.paper-caption')).toContainText('CHƯA BIÊN DỊCH');
 await page.screenshot({path:path.join(out,'tutor-pdf-and-band.png')});
 await page.getByRole('button',{name:'Tạo phiếu LaTeX',exact:true}).click();
 const download=page.waitForEvent('download');
 await page.getByRole('dialog').getByRole('button',{name:'Tải phiếu .tex',exact:true}).click();
 const file=await download;
 await file.saveAs(path.join(out,'ielts-feedback.tex'));
 const source=fs.readFileSync(await file.path(),'utf8');
 expect(source).toContain('\\begin{longtable}');
 expect(source).toContain('TR -- Task Response');
 expect(source).toContain('Bản nháp');
 expect(errors).toEqual([]);
 console.log('LATEX_IELTS_DESIGN_OK text to escaped TeX; submitted source; tutor text/source/PDF mock + band; real .tex report download');
}finally{await browser.close()}
