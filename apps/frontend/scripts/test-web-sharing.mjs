import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const repo=path.resolve('../..'), python=path.resolve(process.argv[2]), home=path.resolve(process.argv[3]);
if(fs.existsSync(home)) throw Error('Use a fresh test home');
fs.mkdirSync(home,{recursive:true});
const factory=process.env.LATEX_TEST_WEB_FACTORY ? [path.resolve(process.env.LATEX_TEST_WEB_FACTORY)] : ['-m','latex_backend.entrypoints.web'];
const server=spawn(python,[...factory,'--home',home,'--port','0','--no-browser'],{cwd:repo,windowsHide:true});
let stdout='',stderr='',browser;
server.stdout.on('data',v=>stdout+=v);server.stderr.on('data',v=>stderr+=v);
try{
    for(let i=0;i<300&&!stdout.includes('OVERLEAF_WEB_READY ');i++){if(server.exitCode!==null)throw Error(stderr);await new Promise(r=>setTimeout(r,100));}
    const line=stdout.split(/\r?\n/).find(v=>v.startsWith('OVERLEAF_WEB_READY '));if(!line)throw Error(stderr);
    const {url}=JSON.parse(line.slice('OVERLEAF_WEB_READY '.length));
    browser=await chromium.launch({channel:'msedge',headless:true});
    const owner=await browser.newContext({viewport:{width:1700,height:1050},permissions:['clipboard-read','clipboard-write']});
    const member=await browser.newContext({viewport:{width:1700,height:1050}});
    const visitor=await browser.newContext({viewport:{width:1700,height:1050}});
    const ownerPage=await owner.newPage(),memberPage=await member.newPage(),visitorPage=await visitor.newPage();
    const errors=[];for(const page of [ownerPage,memberPage,visitorPage])page.on('pageerror',e=>errors.push(String(e)));
    async function signup(context,email,name){
        expect((await context.request.post(url+'api/actions/register',{data:{name,email,password:'browser-password'}})).ok()).toBe(true);
        expect((await context.request.post(url+'api/auth/onboarding',{data:{name,role:'student'}})).ok()).toBe(true);
    }
    await signup(owner,'owner@example.com','Project Owner');
    const created=await owner.request.post(url+'api/projects',{data:{title:'Shared research manuscript'}}), project=await created.json();
    const route=url+`api/projects/${project.id}/sharing`;
    await ownerPage.goto(url);await ownerPage.locator('.project-card-open').click();
    await ownerPage.getByRole('button',{name:'Chia sẻ',exact:true}).click();
    await expect(ownerPage.getByRole('dialog')).toBeVisible();
    await expect(ownerPage.getByLabel('Chế độ chia sẻ',{exact:true})).toHaveValue('private');
    await expect(ownerPage.getByRole('button',{name:'Sao chép liên kết chia sẻ',exact:true})).toBeDisabled();
    await expect(ownerPage.getByLabel('Mời người khác qua email')).toBeVisible();
    await ownerPage.screenshot({path:home+'/share-private.png'});
    await ownerPage.getByLabel('Mời người khác qua email').fill('member@example.com');
    await ownerPage.getByLabel('Quyền của lời mời',{exact:true}).selectOption('viewer');
    await ownerPage.getByRole('button',{name:'Mời',exact:true}).click();
    await expect(ownerPage.getByText('member@example.com',{exact:true})).toBeVisible();
    await ownerPage.getByRole('button',{name:'Sao chép lời mời cho member@example.com',exact:true}).click();
    const invitationLink=await ownerPage.evaluate(()=>navigator.clipboard.readText());
    expect(invitationLink).toContain('#share=');
    // Open the invitation while signed out, then complete account and role onboarding.
    await memberPage.goto(invitationLink);
    await memberPage.getByRole('button',{name:'Đăng ký',exact:true}).click();
    await memberPage.getByLabel('Tên hiển thị',{exact:true}).fill('Invited Member');
    await memberPage.getByLabel('Email',{exact:true}).fill('member@example.com');
    await memberPage.getByLabel('Mật khẩu',{exact:true}).fill('browser-password');
    await memberPage.getByRole('button',{name:'Đăng ký',exact:true}).click();
    await memberPage.getByRole('radio',{name:/Student/}).check();
    await memberPage.getByRole('button',{name:'Vào không gian của tôi',exact:true}).click();
    await expect(memberPage.locator('.cm-content')).toBeVisible();
    await expect(memberPage.locator('.cm-content')).toHaveAttribute('aria-readonly','true');
    const readOnlySource=await memberPage.locator('.cm-content').innerText();
    await memberPage.locator('.cm-content').click();await memberPage.keyboard.type('SHOULD_NOT_BE_INSERTED');
    expect(await memberPage.locator('.cm-content').innerText()).toBe(readOnlySource);
    await expect(memberPage.getByTitle('Thêm tệp',{exact:true})).toBeDisabled();
    await expect(memberPage.locator('.compile-button')).toBeEnabled();
    await memberPage.locator('.compile-button').click();
    await expect(memberPage.locator('.pdf-sheet')).toHaveCount(1,{timeout:60000});
    expect((await member.request.put(url+`api/projects/${project.id}/file`,{data:{path:'main.tex',content:'unauthorized'}})).status()).toBe(403);
    await ownerPage.getByLabel('Quyền của member@example.com',{exact:true}).selectOption('editor');
    await expect(memberPage.locator('.cm-content')).not.toHaveAttribute('aria-readonly','true',{timeout:10000});
    await memberPage.locator('.cm-content').fill('\\documentclass{article}\n\\begin{document}\nSHARED EDITOR SAVED CONTENT\n\\end{document}');
    await memberPage.locator('.save-source').click();
    await expect.poll(async()=>{const r=await owner.request.get(url+`api/projects/${project.id}/file?path=main.tex`);return(await r.json()).content;}).toContain('SHARED EDITOR SAVED CONTENT');
    await memberPage.getByRole('button',{name:'Quay lại danh sách dự án (Thoát)',exact:true}).click();
    await memberPage.getByRole('button',{name:/Được chia sẻ với bạn/}).click();
    await expect(memberPage.locator('.project-card')).toHaveCount(1);
    await expect(memberPage.locator('.project-manage')).toHaveCount(0);
    await ownerPage.getByLabel('Chế độ chia sẻ',{exact:true}).selectOption('link');
    await expect(ownerPage.getByLabel('Quyền của liên kết',{exact:true})).toHaveValue('viewer');
    await ownerPage.getByRole('button',{name:'Sao chép liên kết chia sẻ',exact:true}).click();
    const publicLink=await ownerPage.evaluate(()=>navigator.clipboard.readText());
    await ownerPage.screenshot({path:home+'/share-public.png'});
    await signup(visitor,'visitor@example.com','Link Visitor');
    await visitorPage.goto(publicLink);
    await expect(visitorPage.locator('.cm-content')).toHaveAttribute('aria-readonly','true');
    expect((await visitor.request.get(url+`api/projects/${project.id}/files`)).status()).toBe(200);
    await ownerPage.getByLabel('Chế độ chia sẻ',{exact:true}).selectOption('private');
    await expect(ownerPage.getByRole('button',{name:'Sao chép liên kết chia sẻ',exact:true})).toBeDisabled();
    expect((await visitor.request.get(url+`api/projects/${project.id}/files`)).status()).toBe(404);
    expect((await member.request.get(url+`api/projects/${project.id}/files`)).status()).toBe(200);
    await ownerPage.setViewportSize({width:390,height:844});
    const modal=ownerPage.getByRole('dialog');
    expect((await modal.boundingBox()).width).toBeLessThan(390);
    expect(await modal.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
    const inviteBox=await ownerPage.locator('.share-invite').boundingBox();
    const peopleHeading=await ownerPage.locator('.share-section-heading').boundingBox();
    expect(peopleHeading.y).toBeGreaterThanOrEqual(inviteBox.y+inviteBox.height);
    await ownerPage.screenshot({path:home+'/share-mobile.png'});
    await ownerPage.keyboard.press('Escape');await expect(modal).toHaveCount(0);
    expect(errors).toEqual([]);
    console.log('WEB_SHARING_OK private invitation across signup/role; viewer/editor ACL; shared list; public link; revocation; mobile/keyboard');
}finally{await browser?.close();server.kill('SIGINT');}
