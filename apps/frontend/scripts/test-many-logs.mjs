import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const repo = path.resolve('../..'), python = path.resolve(process.argv[2]), home = path.resolve(process.argv[3]);
if (fs.existsSync(home)) throw Error('Use a fresh test home');
fs.mkdirSync(home, { recursive: true });
const factory = process.env.LATEX_TEST_WEB_FACTORY ? [path.resolve(process.env.LATEX_TEST_WEB_FACTORY)] : ['-m', 'latex_backend.entrypoints.web'];
const server = spawn(python, [...factory, '--home', home, '--port', '0', '--no-browser'], { cwd: repo, windowsHide: true });
let output = '', stderr = '', browser;
server.stdout.on('data', value => output += value); server.stderr.on('data', value => stderr += value);
try {
    for (let i=0; i<300 && !output.includes('OVERLEAF_WEB_READY '); i++) {
        if (server.exitCode !== null) throw Error(stderr);
        await new Promise(resolve => setTimeout(resolve,100));
    }
    const line=output.split(/\r?\n/).find(value=>value.startsWith('OVERLEAF_WEB_READY '));
    if (!line) throw Error(stderr);
    const {url}=JSON.parse(line.slice('OVERLEAF_WEB_READY '.length));
    browser=await chromium.launch({channel:'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1700,height:1000}}), page=await context.newPage();
    const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
    expect((await context.request.post(url+'api/actions/register',{data:{name:'Log Reader',email:'logs@example.com',password:'browser-password'}})).ok()).toBe(true);
    expect((await context.request.post(url+'api/auth/onboarding',{data:{name:'Log Reader',role:'student'}})).ok()).toBe(true);
    const created=await context.request.post(url+'api/projects',{data:{title:'Many compiler warnings'}});
    const project=await created.json();
    const warnings=Array.from({length:120},(_,i)=>`\\PackageWarningNoLine{logtest}{Warning ${String(i+1).padStart(3,'0')}: Detailed compiler warning with a long filename reference chapters/section-${i+1}.tex}`);
    const source=['\\documentclass{article}','\\begin{document}',...warnings,'A document with many warnings.','\\end{document}'].join('\n');
    expect((await context.request.put(url+`api/projects/${project.id}/file`,{data:{path:'main.tex',content:source}})).ok()).toBe(true);
    await page.goto(url);
    await page.locator('.project-card-open').click();
    await page.locator('.compile-button').click();
    await expect(page.locator('.pdf-sheet')).toHaveCount(1,{timeout:60000});
    await expect(page.locator('.compile-button')).toBeEnabled();
    await page.locator('.logs-toggle-btn').click();
    await page.getByRole('tab',{name:/Cảnh báo/}).click();
    const cards=page.locator('.log-card'), list=page.locator('.logs-list-container');
    expect(await cards.count()).toBeGreaterThanOrEqual(120);
    const heights=await cards.evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height));
    expect(Math.min(...heights)).toBeGreaterThanOrEqual(62);
    expect(await list.evaluate(node=>node.scrollHeight>node.clientHeight)).toBe(true);
    const firstWarning=cards.filter({hasText:'Warning 001'}), lastWarning=cards.filter({hasText:'Warning 120'});
    await firstWarning.getByRole('button').click();
    await expect(firstWarning.locator('.log-card-body')).toContainText('Warning 001');
    await firstWarning.getByRole('button').focus();
    await page.keyboard.press('Enter');
    await expect(firstWarning.getByRole('button')).toHaveAttribute('aria-expanded','false');
    await lastWarning.getByRole('button').click();
    await expect(lastWarning.locator('.log-card-body')).toContainText('Warning 120');
    await page.getByRole('button',{name:'Mở tất cả chi tiết',exact:true}).click();
    expect(await page.locator('.log-card-body').count()).toBe(await cards.count());
    expect(Math.min(...await cards.evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height)))).toBeGreaterThan(100);
    await list.evaluate(node=>node.scrollTop=0);
    await page.screenshot({path:path.join(home,'many-logs-light.png')});
    await page.getByRole('button',{name:'Thu gọn chi tiết',exact:true}).click();
    await expect(page.locator('.log-card-body')).toHaveCount(0);
    await page.getByRole('button',{name:'Xem nhật ký thô',exact:true}).click();
    await expect(page.locator('.build-output-raw')).toBeVisible();
    await expect(page.locator('.build-output-raw')).toContainText('Warning 120');
    await expect(page.locator('.raw-logs-section')).toBeInViewport();
    await page.getByRole('tab',{name:/^Lỗi/}).click();
    await expect(cards).toHaveCount(0);
    await page.getByRole('tab',{name:/Tất cả log/}).click();
    expect(await cards.count()).toBeGreaterThanOrEqual(120);
    await page.getByRole('button',{name:'Nhật ký & tệp khác',exact:true}).click();
    const downloadEvent=page.waitForEvent('download');
    await page.getByRole('menuitem',{name:'Tải xuống nhật ký (.log)',exact:true}).click();
    const download=await downloadEvent;
    expect(fs.readFileSync(await download.path(),'utf8')).toContain('Warning 120');
    await page.evaluate(()=>document.documentElement.dataset.mode='dark');
    await list.evaluate(node=>node.scrollTop=0);
    await cards.first().getByRole('button').click();
    await page.screenshot({path:path.join(home,'many-logs-dark.png')});
    expect(errors).toEqual([]);
    console.log('MANY_LOGS_OK 120 actual warnings; readable non-shrinking cards; scroll/keyboard/details/filter/raw log/download; light/dark');
} finally { await browser?.close(); server.kill('SIGINT'); }
